export function localizeMarkup(markup: string, language: Language): string {
  if (language !== "en") return markup;
  let result = markup;
  for (const [source, translated] of Object.entries(english).sort(
    ([a], [b]) => b.length - a.length,
  )) result = result.replaceAll(source, translated);
  return result;
}

export function translateText(text: string, language: Language): string {
  return localizeMarkup(text, language);
}

